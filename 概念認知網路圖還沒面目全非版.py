#去重
summary_points = list(set(all_points))

target_issue="核電"
summary_points = [p for p in all_points if p != target_issue]

model = SentenceTransformer("paraphrase-multilingual-MiniLM-L12-v2");
issue_embedding = model.encode([target_issue])
point_embeddings = model.encode(summary_points)

#提第一列變成2D array中的一維陣列
issue_similarities = cosine_similarity(issue_embedding, point_embeddings)[0]
points_similarities = cosine_similarity(point_embeddings)

nodes = [{"id": target_issue, "size": 60, "group": 0, "relevance_score": 1.0}]
links = []
placed_points = []

#設分支節點門檻
#no_branch_threshold=0.3
branch_threshold=0.3
stop_threshold=0.7    #太相似所以停止的stop_threshold

#由小到大排序後利用[::-1]反轉
sort_issue=np.argsort(issue_similarities)[::-1]

for i in sort_issue:
  point = summary_points[i]
  sim_to_issue = issue_similarities[i]  #抓與issue的相似程度

  #預設連到target_issue
  target_node=target_issue
  link_sim = sim_to_issue
  group_id=1;

  #預設每個點最大相似度都是負無窮大
  max_sim_to_placed = float('-inf')
  best_placed = None

  #高度相似的放大圓圈
  #bigger=0;

  #找是否跟已放置節點更相似
  for place_p in placed_points:
    placed_i = summary_points.index(place_p)
    sim_to_placed = points_similarities[i,placed_i]

    if sim_to_placed > max_sim_to_placed:
      max_sim_to_placed = sim_to_placed
      best_placed = place_p
  if sim_to_issue < branch_threshold:
    print(f"🚫 剔除無關觀點：【{point}】(相似度僅 {sim_to_issue:.2f})")
    continue

  if best_placed and max_sim_to_placed > stop_threshold:
    # 找到原本那個節點，把它變大 (代表這個觀點出現頻率高)
        for node in nodes:
            if node['id'] == best_placed:
                node['size'] += 5 # 每次重複就增加 10
                break
        continue # 跳過，不重複建立節點
#    continue
  if best_placed and max_sim_to_placed > branch_threshold:
    target_node = best_placed
    link_sim = max_sim_to_placed
    group_id = 2

  visual_distance = round(float((1-link_sim)*500+50),2)

  links.append({
      "source": target_node, "sourceLabel":target_node,
      "target": point,  "targetLabel":point,
      "value": float(link_sim),
      "distance": visual_distance
  })
  nodes.append({
      "id": point,
      "size": 65,
      "group": group_id,
      #"relevance_score": float(sim_to_issue)
  })
  placed_points.append(point)

"""輸出json~~~"""

output = {
    "target_issue": target_issue,
    "nodes": nodes,
    "links": links
}
print("--- 輸出 JSON 成果 (前端視覺化用) ---")
print(json.dumps(output, ensure_ascii=False, indent=2))