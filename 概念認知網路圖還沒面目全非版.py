def ollama_summary_points(text):
  system_instruction = (
        "你是一個台灣繁體中文的內容分析助手。"
"請針對使用者提供的文本進行重點摘要"
"規則："
"1. 若有重點，請簡短條列，不需做額外證據說明\n"
"2. 若內容無意義、或純屬寒暄，請直接回覆『無重要資訊』，不要寫任何其他字眼。\n"
"3. 每個論點之間請用『$』符號隔開，不要使用數字編號或換行。\n"
  )
  response = ollama.chat(
      model="gemma3:4b",
      messages=[
          {'role': 'system', 'content': system_instruction},
          {'role': 'user', 'content': f"內容如下：\n{text}"}
      ],
      options={'temperature': 0}
  )
  content = response['message']['content'].strip()
  if "無重要資訊" in content:
    return []
  points = [p.strip().replace('*', '').replace("，","<br>") for p in content.split('$') if p.strip()]
  return points
